// Crear la instancia de i18n
const i18n = new I18n({
  en,
  es,
});

// Configuración
i18n.enableFallback = true;
i18n.defaultLocale = 'es';

export const initI18n = async (): Promise<string> => {
  try {
    const savedLanguage = await AsyncStorage.getItem('@app_language');

    const deviceLanguage =
      Localization.getLocales()[0]?.languageCode ?? 'es';

    const locale = savedLanguage || deviceLanguage;

    i18n.locale = locale;

    return locale;
  } catch (error) {
    i18n.locale = 'es';
    return 'es';
  }
};

export const setLocale = async (locale: string): Promise<void> => {
  i18n.locale = locale;
  await AsyncStorage.setItem('@app_language', locale);
};

export const t = (
  scope: string,
  options?: Record<string, unknown>
): string => i18n.t(scope, options);

export default i18n;